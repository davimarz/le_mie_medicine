create schema if not exists private;

-- Usernames are display names, not globally unique identifiers.
do $$
declare constraint_name text;
begin
  select conname into constraint_name from pg_constraint
  where conrelid = 'public.profiles'::regclass and contype = 'u'
    and conkey = array[(select attnum from pg_attribute where attrelid='public.profiles'::regclass and attname='username')];
  if constraint_name is not null then execute format('alter table public.profiles drop constraint %I', constraint_name); end if;
end $$;

